import type { AnalysisResult } from './types';
import { mdEscape, truncate } from './util';

function severityCounts(a: AnalysisResult): Record<string, number> {
  const counts: Record<string, number> = { critical: 0, high: 0, medium: 0, low: 0, info: 0 };
  for (const f of a.findings) counts[f.severity] += 1;
  return counts;
}

export function generateMarkdown(a: AnalysisResult, aiBrief?: string | null): string {
  const counts = severityCounts(a);
  const L: string[] = [];
  const date = new Date(a.scannedAt).toISOString().replace('T', ' ').slice(0, 19) + ' UTC';

  L.push(`# BLACKBOX // REVERSE ENGINEERING REPORT`);
  L.push(``);
  L.push(`> **Target:** \`${a.projectName}\`  `);
  L.push(`> **Scanned:** ${date} · ${a.durationMs}ms  `);
  L.push(`> **Verdict:** Grade **${a.grade}** — ${a.riskLabel} (score ${a.score}/100)`);
  L.push(``);
  L.push(`*Generated by [BLACKBOX](https://github.com) — AI Software Reverse Engineering Lab. Static analysis only; no code was executed.*`);
  L.push(``);
  L.push(`---`);
  L.push(``);
  L.push(`## 1. Executive Summary`);
  L.push(``);
  L.push(`| Metric | Value |`);
  L.push(`|---|---|`);
  L.push(`| Files analyzed | ${a.totals.files} |`);
  L.push(`| Total size | ${(a.totals.bytes / 1024).toFixed(1)} KB |`);
  L.push(`| Lines of code | ${a.totals.codeLines.toLocaleString()} (${a.totals.lines.toLocaleString()} total incl. blanks/comments) |`);
  L.push(`| Languages | ${a.languages.slice(0, 4).map((l) => mdEscape(l.language)).join(', ') || '—'} |`);
  L.push(`| Frameworks | ${a.frameworks.length ? a.frameworks.map(mdEscape).join(', ') : 'none detected'} |`);
  L.push(`| Project type | ${a.projectTypes.map(mdEscape).join(', ')} |`);
  L.push(`| Dependencies | ${a.dependencies.length} (${a.dependencies.filter((d) => d.type === 'runtime').length} runtime · ${a.dependencies.filter((d) => d.type === 'dev').length} dev) |`);
  L.push(`| API routes mapped | ${a.routes.length} |`);
  L.push(`| Client HTTP calls | ${a.calls.length} (${a.calls.filter((c) => c.external).length} external) |`);
  L.push(`| Security findings | ${a.findings.length} — **${counts.critical} critical**, ${counts.high} high, ${counts.medium} medium |`);
  L.push(`| Vulnerable deps (built-in DB) | ${a.advisories.length} |`);
  L.push(``);
  L.push(`---`);
  L.push(``);
  L.push(`## 2. Project Profile`);
  L.push(``);
  L.push(`**Detected technologies:** ${a.frameworks.length ? a.frameworks.join(' · ') : 'n/a'}`);
  L.push(``);
  L.push(`**Project classification:** ${a.projectTypes.join(' · ')}`);
  L.push(``);
  if (a.entryPoints.length) {
    L.push(`**Entry points / CI:**`);
    for (const e of a.entryPoints) L.push(`- \`${mdEscape(e)}\``);
    L.push(``);
  }
  if (a.scripts.length) {
    L.push(`### How to run (detected scripts)`);
    L.push(``);
    L.push('```bash');
    if (a.dependencies.some((d) => d.manager === 'npm')) L.push('npm install');
    if (a.dependencies.some((d) => d.manager === 'pip')) L.push('pip install -r requirements.txt');
    for (const s of a.scripts.slice(0, 10)) L.push(`npm run ${s.name}   # ${s.command}`);
    L.push('```');
    L.push(``);
  }
  L.push(`---`);
  L.push(``);
  L.push(`## 3. Codebase Composition`);
  L.push(``);
  L.push(`### Language breakdown`);
  L.push(``);
  L.push(`| Language | Files | Lines | % |`);
  L.push(`|---|---|---|---|`);
  for (const l of a.languages) {
    L.push(`| ${mdEscape(l.language)} | ${l.files} | ${l.lines.toLocaleString()} | ${l.pct.toFixed(1)}% |`);
  }
  L.push(``);
  L.push(`### Top directories`);
  L.push(``);
  L.push(`| Directory | Files | Lines | Size |`);
  L.push(`|---|---|---|---|`);
  for (const d of a.topDirs) {
    L.push(`| \`${mdEscape(d.name)}\` | ${d.files} | ${d.lines.toLocaleString()} | ${(d.bytes / 1024).toFixed(1)} KB |`);
  }
  L.push(``);
  L.push(`---`);
  L.push(``);
  L.push(`## 4. Dependency Inventory`);
  L.push(``);
  if (a.dependencies.length === 0) {
    L.push(`No dependency manifests detected.`);
  } else {
    const byManager = new Map<string, typeof a.dependencies>();
    for (const d of a.dependencies) {
      const list = byManager.get(d.manager) ?? [];
      list.push(d);
      byManager.set(d.manager, list);
    }
    for (const [manager, deps] of byManager) {
      L.push(`### ${manager} (${deps.length})`);
      L.push(``);
      L.push(`| Package | Version | Type |`);
      L.push(`|---|---|---|`);
      for (const d of deps.slice(0, 60)) {
        L.push(`| \`${mdEscape(d.name)}\` | \`${mdEscape(d.version)}\` | ${d.type} |`);
      }
      if (deps.length > 60) L.push(`| … and ${deps.length - 60} more | | |`);
      L.push(``);
    }
  }
  if (a.advisories.length) {
    L.push(`### ⚠ Dependency advisories (built-in offline database)`);
    L.push(``);
    L.push(`| Package | Version | Severity | Issue | Fix |`);
    L.push(`|---|---|---|---|---|`);
    for (const adv of a.advisories) {
      L.push(`| \`${mdEscape(adv.name)}\` | \`${mdEscape(adv.version)}\` | **${adv.severity.toUpperCase()}** | ${mdEscape(adv.title)} | ${mdEscape(adv.fix)} |`);
    }
    L.push(``);
  }
  L.push(`---`);
  L.push(``);
  L.push(`## 5. API Surface`);
  L.push(``);
  if (a.routes.length === 0 && a.calls.length === 0) {
    L.push(`No API routes or HTTP calls were detected statically.`);
  } else {
    if (a.routes.length) {
      L.push(`### Server routes (${a.routes.length})`);
      L.push(``);
      L.push(`| Method | Path | Framework | Location |`);
      L.push(`|---|---|---|---|`);
      for (const r of a.routes.slice(0, 120)) {
        L.push(`| \`${r.method}\` | \`${mdEscape(r.path)}\` | ${mdEscape(r.framework)} | \`${mdEscape(r.file)}:${r.line}\` |`);
      }
      if (a.routes.length > 120) L.push(`| … | … ${a.routes.length - 120} more routes | | |`);
      L.push(``);
    }
    if (a.calls.length) {
      L.push(`### Client-side HTTP calls (${a.calls.length})`);
      L.push(``);
      L.push(`| Method | URL | Client | Scope | Matched route |`);
      L.push(`|---|---|---|---|---|`);
      for (const c of a.calls.slice(0, 120)) {
        L.push(`| \`${c.method}\` | \`${mdEscape(truncate(c.url, 80))}\` | ${mdEscape(c.client)} | ${c.external ? 'external' : 'internal'} | ${c.matchedRoute ? `\`${mdEscape(c.matchedRoute)}\`` : '—'} |`);
      }
      if (a.calls.length > 120) L.push(`| … | … ${a.calls.length - 120} more calls | | | |`);
      L.push(``);
    }
  }
  L.push(`---`);
  L.push(``);
  L.push(`## 6. Security Assessment`);
  L.push(``);
  L.push(`**Score: ${a.score}/100 — Grade ${a.grade} — ${a.riskLabel}**`);
  L.push(``);
  L.push(`| Severity | Count |`);
  L.push(`|---|---|`);
  for (const sev of ['critical', 'high', 'medium', 'low', 'info'] as const) {
    L.push(`| ${sev.toUpperCase()} | ${counts[sev]} |`);
  }
  L.push(``);
  if (a.findings.length) {
    L.push(`### Findings`);
    L.push(``);
    for (const sev of ['critical', 'high', 'medium', 'low', 'info'] as const) {
      const group = a.findings.filter((f) => f.severity === sev);
      if (group.length === 0) continue;
      L.push(`#### ${sev.toUpperCase()} (${group.length})`);
      L.push(``);
      for (const f of group) {
        const loc = f.line > 0 ? `${f.file}:${f.line}` : f.file;
        L.push(`- **[${f.ruleId}] ${mdEscape(f.title)}** — \`${mdEscape(loc)}\``);
        L.push(`  - ${mdEscape(f.description)}`);
        L.push(`  - **Fix:** ${mdEscape(f.remediation)}`);
        if (f.snippet && f.line > 0) L.push(`  - \`${mdEscape(truncate(f.snippet, 160))}\``);
      }
      L.push(``);
    }
  } else {
    L.push(`No findings from the built-in rule set. ⚠ Absence of findings ≠ proof of security — this scan is heuristic and offline.`);
    L.push(``);
  }
  L.push(`---`);
  L.push(``);
  L.push(`## 7. Architecture (Mermaid)`);
  L.push(``);
  const arch = a.diagrams.find((d) => d.id === 'architecture');
  if (arch) {
    L.push('```mermaid');
    L.push(arch.mermaid);
    L.push('```');
    L.push(``);
  }
  L.push(`---`);
  L.push(``);
  L.push(`## 8. Remediation Roadmap`);
  L.push(``);
  let step = 1;
  if (counts.critical > 0) L.push(`${step++}. **Immediately rotate** any committed secrets listed above and purge them from git history.`);
  if (a.advisories.length > 0) L.push(`${step++}. **Upgrade vulnerable dependencies** listed in §4 (run in a branch, re-run the full test suite).`);
  if (counts.high > 0) L.push(`${step++}. **Fix HIGH findings** in §6 — injection sinks, TLS bypasses and exposed credentials.`);
  if (a.calls.some((c) => c.external)) L.push(`${step++}. **Catalog external calls** (§5) and confirm every third-party endpoint is intended, TLS-only and monitored.`);
  if (a.routes.length > 0) L.push(`${step++}. **Add authn/authz + rate limiting** on the ${a.routes.length} mapped routes; verify each route is reachable only with a valid session/token.`);
  L.push(`${step++}. Add CI gates: dependency audit (npm audit / pip-audit), secret scanning (gitleaks) and this report's rule set on every PR.`);
  L.push(`${step++}. Write/refresh developer docs from this report and keep it in the repo; regenerate on every release.`);
  L.push(``);
  if (aiBrief && aiBrief.trim()) {
    L.push(`---`);
    L.push(``);
    L.push(`## Appendix A — AI Architecture Assessment`);
    L.push(``);
    L.push(aiBrief.trim());
    L.push(``);
  }
  L.push(`---`);
  L.push(``);
  L.push(`## Appendix B — File Inventory (largest 40)`);
  L.push(``);
  L.push(`| File | Language | Lines | Size |`);
  L.push(`|---|---|---|---|`);
  const largest = [...a.files].sort((x, y) => y.size - x.size).slice(0, 40);
  for (const f of largest) {
    L.push(`| \`${mdEscape(f.path)}\` | ${mdEscape(f.language ?? '—')} | ${f.lines.toLocaleString()} | ${(f.size / 1024).toFixed(1)} KB |`);
  }
  L.push(``);
  L.push(`*Report generated by BLACKBOX · static analysis, no code executed · findings are heuristic — verify before acting.*`);
  return L.join('\n');
}
